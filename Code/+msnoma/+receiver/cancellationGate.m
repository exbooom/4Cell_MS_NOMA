function gate = cancellationGate(fit,opts)
%CANCELLATIONGATE Conservative operating policy using fitted data only.
% Residual dominance is not a delay-accuracy bound or a false-alarm test.
gate=struct('eligible',false,'status','fit_invalid', ...
    'precisionPassed',false,'residualPassed',false, ...
    'maximumRelativeResidualEnergy',opts.maximumRelativeResidualEnergy);
if ~fit.valid, return; end
gate.precisionPassed=all(isfinite(fit.gaussianDelayStdSamples)) ...
    && all(isfinite(fit.gaussianRelativeGainStd)) ...
    && all(fit.gaussianDelayStdSamples<=opts.maximumDelayStdSamples) ...
    && all(fit.gaussianRelativeGainStd<=opts.maximumRelativeGainStd);
gate.residualPassed=isfinite(fit.relativeResidualEnergy) ...
    && fit.relativeResidualEnergy>=0 ...
    && fit.relativeResidualEnergy<=opts.maximumRelativeResidualEnergy;
gate.status='Gaussian_precision_gate_failed';
if ~gate.precisionPassed, return; end
gate.status='residual_dominance_gate_failed';
if ~gate.residualPassed, return; end
gate.eligible=true; gate.status='precision_and_residual_gates_passed';
end
