function exportReceiverAudit(run,runDir)
%EXPORTRECEIVERAUDIT Preserve distinct point and filtered PSD receiver models.
c=run.prsComparison;
if ~isfield(c,'receiverAudit') || ~isfield(c.receiverAudit,'filteredService'), return; end
a=c.receiverAudit; [bs,carrier,tx]=ndgrid(1:run.num.K,1:run.num.N,1:run.num.K);
p=a.pointService; f=a.filteredService;
t=table(bs(:),carrier(:),tx(:),bs(:)~=tx(:),a.pointUnitPsdWPerHzPerW(:), ...
    a.filteredUnitPsdWPerHzPerW(:),p.berDuringPrsSlot(:),f.berDuringPrsSlot(:), ...
    'VariableNames',{'communicationServingBS','carrierAndReceiverId','prsTransmittingBS', ...
    'communicationActive','pointPsdPerW','filteredPsdPerW','pointSlotBer','filteredSlotBer'});
writetable(t,fullfile(runDir,'prs_receiver_filter_links.csv'));
t=table((1:run.num.K)',p.communicationOpportunityFraction,max(p.worstActiveBer,[],2), ...
    max(f.worstActiveBer,[],2),p.activeSlotBerQosMet,f.activeSlotBerQosMet, ...
    p.serviceContractMet,f.serviceContractMet,sum(p.expectedCorrectBitRatePerCarrierBps,2), ...
    sum(f.expectedCorrectBitRatePerCarrierBps,2),'VariableNames', ...
    {'baseStation','communicationOpportunityFraction','pointWorstBer','filteredWorstBer', ...
    'pointActiveBerQosMet','filteredActiveBerQosMet','pointServiceMet','filteredServiceMet', ...
    'pointExpectedCorrectBitsPerS','filteredExpectedCorrectBitsPerS'});
writetable(t,fullfile(runDir,'prs_receiver_filter_service.csv'));
end
