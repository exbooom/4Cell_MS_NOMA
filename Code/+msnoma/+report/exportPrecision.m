function exportPrecision(run,runDir)
%EXPORTPRECISION Separate exact-DLL comparisons and power-matched PRS example.
for i=1:numel(run.algorithms)
    a=run.algorithms(i);
    if isempty(a.evaluation) || ~isfield(a.evaluation,'integral'), continue; end
    e=a.evaluation;
    v=e.integral;
    [k,m]=ndgrid(1:run.num.K,v.userIds);
    two=e.twoTerm.rangeVarianceM2(:,v.userIds);
    three=e.threeTerm.rangeVarianceM2(:,v.userIds);
    t=table(k(:),m(:),v.delayVarianceS2(:),v.rangeVarianceM2(:),two(:),three(:), ...
        v.noiseDelayVarianceS2(:),v.communicationDelayVarianceS2(:), ...
        v.positioningDelayVarianceS2(:),v.twoTermRelativeVarianceError(:), ...
        v.threeTermRelativeVarianceError(:),'VariableNames',{'baseStation', ...
        'positioningUser','integralDelayVarianceS2','integralRangeVarianceM2', ...
        'twoTermRangeVarianceM2','threeTermRangeVarianceM2','noiseDelayVarianceS2', ...
        'communicationDelayVarianceS2','positioningDelayVarianceS2', ...
        'twoTermRelativeVarianceError','threeTermRelativeVarianceError'});
    writetable(t,fullfile(runDir,[a.id '_dll_validation.csv']));
end
if ~isempty(run.integralKernel)
    q=run.integralKernel;
    t=table(q.userIds',q.converged',q.samplesPerCarrier',q.relativeChange', ...
        q.localBoundsHz(:,1),q.localBoundsHz(:,2),'VariableNames', ...
        {'positioningUser','converged','samplesPerCarrier','maxRelativeChange', ...
        'localLowerHz','localUpperHz'});
    writetable(t,fullfile(runDir,'dll_quadrature.csv'));
end
p=run.prsBenchmark;
if ~isfield(p,'position') || isempty(p.position), return; end
b=p.budget;
t=table((1:run.num.K)',b.averagePowerW,b.energyPerMeasurementJ,b.symbolCount, ...
    b.instantaneousPowerW,b.observationTimeS,b.dutyCycle,b.slotStartS,b.feasible, ...
    'VariableNames',{'baseStation','averagePowerW','broadcastEnergyJ', ...
    'symbolCount','instantaneousPowerW','observationTimeS','dutyCycle','slotStartS','feasible'});
writetable(t,fullfile(runDir,'prs_broadcast_budget.csv'));
t=table((1:run.num.M)',p.position.valid,p.position.positionStdM, ...
    'VariableNames',{'positioningUser','geometryValid','prsPositionBoundM'});
writetable(t,fullfile(runDir,'prs_positions.csv'));
[k,m]=ndgrid(1:run.num.K,1:run.num.M);
t=table(k(:),m(:),p.crb.delayVarianceS2(:),p.crb.rangeVarianceM2(:), ...
    'VariableNames',{'baseStation','positioningUser','delayVarianceS2','rangeVarianceM2'});
writetable(t,fullfile(runDir,'prs_ranging.csv'));
end
