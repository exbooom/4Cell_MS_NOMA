function exportDllBias(run,runDir)
%EXPORTDLLBIAS Full controlled family, matched pairs and telescoping attribution.
b=run.dllBias;
if ~isfield(b,'result'), return; end
r=b.result; K=run.num.K; ids=r.userIds; V=numel(r.variantIds);
[bs,user,variant]=ndgrid(1:K,ids,1:V);
names=reshape(r.variantIds(variant(:)),[],1);
t=table(bs(:),user(:),names,r.flags(variant(:),1),r.flags(variant(:),2),r.flags(variant(:),3), ...
    r.delayVarianceS2(:),r.noiseDelayVarianceS2(:),r.communicationDelayVarianceS2(:), ...
    r.positioningDelayVarianceS2(:),r.relativeToBaseline(:),'VariableNames', ...
    {'baseStation','positioningUser','variant','linearizedSine','spectralLines','localFrontend', ...
    'delayVarianceS2','noiseVarianceS2','communicationVarianceS2','positioningVarianceS2','relativeToBaseline'});
writetable(t,fullfile(runDir,'dll_bias_variants.csv'));
[bs,user]=ndgrid(1:K,ids); count=numel(bs); pairs=cell(numel(r.pairedContrasts),1);
for i=1:numel(pairs)
    p=r.pairedContrasts(i);
    pairs{i}=table(bs(:),user(:),repmat({p.factor},count,1), ...
        repmat(r.variantIds(p.fromIndex),count,1),repmat(r.variantIds(p.toIndex),count,1), ...
        p.absoluteDifferenceS2(:),p.relativeToFrom(:),p.logVarianceRatio(:),'VariableNames', ...
        {'baseStation','positioningUser','factor','fromVariant','toVariant', ...
        'absoluteVarianceDifferenceS2','relativeToFrom','logVarianceRatio'});
end
writetable(vertcat(pairs{:}),fullfile(runDir,'dll_bias_paired_contrasts.csv'));
[bs,user,step]=ndgrid(1:K,ids,1:6);
before=r.chainVarianceS2(:,:,1:end-1); after=r.chainVarianceS2(:,:,2:end);
t=table(bs(:),user(:),step(:),reshape(r.chainStepIds(step(:)),[],1), ...
    before(:),after(:),r.chainDifferenceS2(:),r.chainRelativeToBaseline(:), ...
    r.chainRelativeToPrevious(:),'VariableNames',{'baseStation','positioningUser','step','effect', ...
    'beforeVarianceS2','afterVarianceS2','differenceS2','differenceRelativeToBaseline','differenceRelativeToPrevious'});
writetable(t,fullfile(runDir,'dll_bias_chain.csv'));
[user,variant]=ndgrid(ids,1:V);
t=table(user(:),reshape(r.variantIds(variant(:)),[],1),r.positionStdM(:), ...
    'VariableNames',{'positioningUser','variant','fixedOraclePositionStdM'});
writetable(t,fullfile(runDir,'dll_bias_positions.csv'));
records=cell(V,1); summary=cell(9,1);
for i=1:V
    k=b.bundle.variants(i).kernel;
    records{i}=table(ids(:),repmat(r.variantIds(i),numel(ids),1),k.A0PerS(:), ...
        k.noiseIntegral(:),k.communicationIntegralS(:),k.positioningIntegralS(:), ...
        k.relativeChange(:),k.samplesPerCarrier(:),k.converged(:), ...
        k.localBoundsHz(:,1),k.localBoundsHz(:,2),'VariableNames', ...
        {'positioningUser','variant','slopePerS','noiseIntegral','communicationIntegralS', ...
        'positioningIntegralS','quadratureRelativeChange','samplesPerCarrier','converged','lowerHz','upperHz'});
end
writetable(vertcat(records{:}),fullfile(runDir,'dll_bias_kernels.csv'));
for i=1:9
    if i<=3
        value=r.mainEffectRelativeToBaseline(:,:,i); effect=b.bundle.factorOrder{i}; type='single_factor_at_baseline';
    else
        value=r.chainRelativeToBaseline(:,:,i-3); effect=r.chainStepIds{i-3}; type='ordered_chain_step';
    end
    summary{i}=struct('comparisonType',type,'effect',effect,'minimumRelativeVarianceDifference',min(value(:)), ...
        'maximumRelativeVarianceDifference',max(value(:)),'meanRelativeVarianceDifference',mean(value(:)), ...
        'maximumAbsoluteRelativeVarianceDifference',max(abs(value(:))), ...
        'selectedLinks',numel(value),'quadratureAllConverged',r.allConverged, ...
        'maximumRelativeClosureResidual',r.maximumRelativeClosureResidual);
end
writetable(struct2table(vertcat(summary{:})),fullfile(runDir,'dll_bias_effect_summary.csv'));
end
