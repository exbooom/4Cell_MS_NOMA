function exportPChannels(study,folder,prefix)
%EXPORTPCHANNELS Estimated P-channel diagnostics without substituting truth.
if ~isfield(study,'estimatedPChannels'), return; end
rows=cell(numel(study.estimatedPChannels),1);
for u=1:numel(rows)
    f=study.estimatedPChannels{u}; if isempty(f), continue; end
    K=numel(f.delayS);
    rows{u}=table(repmat(study.userIds(u),K,1),(1:K)',repmat(f.valid,K,1), ...
        repmat(string(f.status),K,1),f.delayS,real(f.complexGain),imag(f.complexGain), ...
        repmat(f.iterations,K,1),repmat(f.rankRatio,K,1), ...
        repmat(f.relativeResidualEnergy,K,1),f.gaussianDelayStdSamples, ...
        f.gaussianRelativeGainStd,repmat(f.cancellationEligible,K,1), ...
        repmat(string(f.eligibilityStatus),K,1), ...
        repmat(f.precisionGatePassed,K,1),repmat(f.residualGatePassed,K,1), ...
        repmat(f.maximumRelativeResidualEnergy,K,1),'VariableNames', ...
        {'positioningUser','baseStation','fitValid','fitStatus','estimatedDelayS', ...
        'estimatedGainReal','estimatedGainImag','iterations','rankRatio','relativeResidualEnergy', ...
        'GaussianDelayStdSamples','GaussianRelativeGainStd','cancellationEligible','eligibilityStatus', ...
        'precisionGatePassed','residualGatePassed','maximumRelativeResidualEnergy'});
end
nonempty=~cellfun(@isempty,rows);
if any(nonempty)
    writetable(vertcat(rows{nonempty}),fullfile(folder,[prefix '_estimated_P_channels.csv']));
end
end
