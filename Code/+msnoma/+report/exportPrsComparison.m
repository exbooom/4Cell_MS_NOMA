function exportPrsComparison(run,runDir)
%EXPORTPRSCOMPARISON Separate geometry, active BER, service and time contracts.
c=run.prsComparison;
if ~isfield(c,'policies') || isempty(c.policies), return; end
summary=cell(1,numel(c.policies));
for i=1:numel(c.policies)
    p=c.policies(i); s=p.service; K=run.num.K; M=run.num.M;
    t=table((1:K)',s.communicationOpportunityFraction,s.activeCommunicationPowerW, ...
        s.averageCommunicationPowerW,s.requiredPowerForEqualCommunicationEnergyW, ...
        s.energyCompensationPeakFeasible,s.communicationEnergyMatched, ...
        s.operatingPowerFeasible,s.activeSlotBerQosMet,s.attemptedRateContractMet, ...
        s.serviceContractMet,s.energyAndServiceMatched,s.failureReason, ...
        'VariableNames',{'baseStation','communicationOpportunityFraction','activePowerW', ...
        'averagePowerW','equalEnergyRequiredActivePowerW','compensationPeakFeasible', ...
        'communicationEnergyMatched','operatingPowerFeasible','activeSlotBerQosMet', ...
        'attemptedRateContractMet','serviceContractMet','energyAndServiceMatched','failureReason'});
    writetable(t,fullfile(runDir,['prs_' p.id '_service.csv']));
    [bs,carrier]=ndgrid(1:K,1:run.num.N);
    attempted=repmat(s.attemptedBitRatePerCarrierBps,1,run.num.N);
    t=table(bs(:),carrier(:),s.referenceBer(:),s.meanActiveBer(:),s.worstActiveBer(:), ...
        attempted(:),s.expectedCorrectBitRatePerCarrierBps(:), ...
        s.referenceExpectedCorrectBitRatePerCarrierBps(:),'VariableNames', ...
        {'baseStation','carrier','msReferenceBer','meanActivePrsScheduleBer', ...
        'worstActivePrsScheduleBer','attemptedBitsPerS','expectedCorrectBitsPerS','msExpectedCorrectBitsPerS'});
    writetable(t,fullfile(runDir,['prs_' p.id '_communication.csv']));
    t=table((1:M)',c.msTdoaCommon.valid,c.msTdoaCommon.positionStdM, ...
        c.msTdoaHearable.valid,c.msTdoaHearable.positionStdM,p.tdoa.valid, ...
        p.tdoa.positionStdM,p.tdoa.referenceBs,p.tdoa.failureReason, ...
        'VariableNames',{'positioningUser','msCommonMaskValid','msCommonMaskTdoaStdM', ...
        'msHearableMaskValid','msHearableMaskTdoaStdM','prsOracleGeometryValid', ...
        'prsTdoaBoundM','prsReferenceBs','prsGeometryReason'});
    writetable(t,fullfile(runDir,['prs_' p.id '_tdoa.csv']));
    [bs,user]=ndgrid(1:K,1:M);
    t=table(bs(:),user(:),p.crb.delayVarianceS2(:),p.crb.rangeVarianceM2(:), ...
        'VariableNames',{'baseStation','positioningUser','delayVarianceS2','rangeVarianceM2'});
    writetable(t,fullfile(runDir,['prs_' p.id '_ranging.csv']));
    g=p.tdoa.valid;
    value=NaN; if any(g), value=mean(p.tdoa.positionStdM(g)); end
    summary{i}=struct('policy',p.id,'nTotal',M,'oracleGeometryValid',nnz(g), ...
        'conditionalMeanPrsTdoaM',value,'minimumCommunicationFraction',min(s.communicationOpportunityFraction), ...
        'worstActiveBer',max(s.worstActiveBer(:)), ...
        'communicationServiceMet',all(s.serviceContractMet), ...
        'operatingPowerFeasible',all(s.operatingPowerFeasible), ...
        'communicationEnergyMatched',all(s.communicationEnergyMatched), ...
        'energyCompensationPeakFeasible',all(s.energyCompensationPeakFeasible), ...
        'positioningBroadcastEnergyMatched',c.positioningBroadcastEnergyMatched, ...
        'geometryConventionMatched',c.geometryConventionMatched, ...
        'observationMatched',c.observationMatched,'detectionCoverageEvaluated',c.detectionCoverageEvaluated, ...
        'fullyMatched',c.fullyMatched);
end
writetable(struct2table(vertcat(summary{:})),fullfile(runDir,'prs_comparison_summary.csv'));
end
