function opts = sampledDefaults(cfg)
%SAMPLEDDEFAULTS Explicit engineering choices for finite packet acquisition.
corners=[cfg.assumed.domainM(1,[1,2,2,1])',cfg.assumed.domainM(2,[1,1,2,2])'];
maximum=0;
for k=1:cfg.paper.K
    maximum=max(maximum,max(sqrt(sum((corners-cfg.paper.bsPosM(k,:)).^2,2))));
end
opts=struct('enabled',false,'referenceAlgorithm','central','userIds',[], ...
    'oversampling',4,'codeChips',1023,'codeMode','author_L1CP', ...
    'sequenceSeed',1701,'noiseSeed',2701,'noiseMultiplier',1, ...
    'maximumRangeM',ceil(1.1*maximum),'maximumFftLength',2^21, ...
    'includeCommunication',true,'carrierHz',cfg.paper.carrierHz, ...
    'whitening','known_average_CP_psd','whiteningFloorFraction',1e-10, ...
    'falseAlarmProbability',1e-4,'delayToleranceSamples',1e-5,'coarseOversampling',4, ...
    'interferenceCancellation',struct('enabled',false,'maxIterations',30, ...
        'maxBacktracks',15,'maximumStepSamples',1,'delayToleranceSamples',1e-4, ...
        'rankTolerance',1e-10,'maximumDelayStdSamples',0.25,'maximumRelativeGainStd',0.25, ...
        'maximumRelativeResidualEnergy',0.5), ...
    'position',struct('maxIterations',100,'gradientToleranceM',1e-6, ...
        'positionToleranceM',1e-7,'rankTolerance',1e-10,'maximumResidualRmsM',10, ...
        'domainM',cfg.assumed.domainM));
end
